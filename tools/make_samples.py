def png_with_text():
    buf = io.BytesIO()
    Image.new("RGB", (60, 40), (40, 120, 200)).save(buf, "PNG")
    data = buf.getvalue()

    def chunk(t, payload):
        return struct.pack(">I", len(payload)) + t + payload + struct.pack(">I", zlib.crc32(t + payload) & 0xffffffff)

    extra = chunk(b"tEXt", b"Software\x00matplotlib version 3.9.0, https://matplotlib.org/") + \
            chunk(b"caBX", b"c2pa manifest: OpenAI DALL-E")
    return data[:33] + extra + data[33:]  # после IHDR


def jpeg_with_exif():
    img = Image.new("RGB", (60, 40), (200, 80, 40))
    exif = img.getexif()
    exif[0x0131] = "DALL-E 3 (OpenAI)"  # Software
    exif[0x013B] = "ChatGPT"            # Artist
    buf = io.BytesIO()
    img.save(buf, "JPEG", exif=exif.tobytes(), comment=b"Generated by AI")
    return buf.getvalue()


