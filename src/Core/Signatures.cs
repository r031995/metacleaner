using System.Text.RegularExpressions;

namespace MetaCleaner.Core;

/// <summary>Шаблоны, по которым распознаются следы ИИ и программ-генераторов.</summary>
public static class Signatures
{
    const RegexOptions O = RegexOptions.IgnoreCase | RegexOptions.CultureInvariant | RegexOptions.Compiled;

    /// <summary>Упоминания ИИ-сервисов и моделей.</summary>
    public static readonly Regex Ai = new(
        @"chat\s?gpt|openai|\bgpt-?[345]|\bgpt-?4o|dall[\s·\-]?e|\bclaude\b|anthropic|\bgemini\b|\bbard\b|copilot|deepseek|" +
        @"gigachat|гигачат|yandex\s?gpt|яндекс\s?gpt|midjourney|stable[\s\-]?diffusion|firefly|perplexity|mistral|" +
        @"\bllama\b|\bqwen\b|нейросет|сгенерирова|generated by|ai[\s\-_]generated|\bc2pa\b", O);

    /// <summary>Программы и библиотеки, которыми документы собирают автоматически.</summary>
    public static readonly Regex Generator = new(
        @"python-docx|python-pptx|openpyxl|xlsxwriter|docx4j|apache\s?poi|aspose|phpword|phpspreadsheet|phpexcel|" +
        @"maarten balliauw|unknown creator|officegen|\bun-named\b|pandoc|docxtemplater|syncfusion|gembox|" +
        @"spire\.(doc|xls|presentation)|exceljs|sheetjs|closedxml|epplus|\bnpoi\b|reportlab|pptxgenjs|" +
        @"\bdocx\.js\b|html-docx|mammoth|steve canny", O);

    /// <summary>Даты создания (UTC) из встроенных шаблонов библиотек-генераторов.</summary>
    public static readonly (DateTime Utc, string Tool)[] TemplateDates =
    {
        (new DateTime(2013, 12, 23, 23, 15, 0, DateTimeKind.Utc), "python-docx"),
        (new DateTime(2013, 1, 27, 9, 14, 0, DateTimeKind.Utc), "python-pptx"),
    };

    /// <summary>Ссылки на ИИ-сервисы.</summary>
    public static readonly Regex AiDomain = new(
        @"chatgpt\.com|chat\.openai\.com|openai\.com|claude\.ai|anthropic\.com|gemini\.google\.com|bard\.google\.com|" +
        @"perplexity\.ai|copilot\.microsoft\.com|deepseek\.com|poe\.com|giga\.chat|gigachat|alice\.yandex|" +
        @"you\.com|character\.ai|mistral\.ai", O);

    /// <summary>Метка, которую ChatGPT и др. добавляют в ссылки из ответов.</summary>
    public static readonly Regex AiUtmParam = new(
        @"^utm_source=(chatgpt\.com|chat\.openai\.com|openai(\.com)?|perplexity(\.ai)?|claude\.ai|copilot(\.microsoft\.com)?|gemini(\.google\.com)?)$", O);

    // ----- текст документа -----

    public static readonly Regex AiPhrases = new(
        @"как (ии|искусственный интеллект|языковая модель|модель ии)|я не могу (предоставить|помочь|выполнить)|" +
        @"надеюсь, (это|эта информация) (поможет|будет полезн|было полезн)|конечно[!,] вот|" +
        @"вот (обновл|исправл|переработ|доработ)\w* (вариант|версия|текст)|дата отсечения знаний|" +
        @"as an ai|as a language model|i hope this helps|certainly[!,] here|" +
        @"here(?:'|’)s (?:a|an|the) (?:revised|updated|improved)|knowledge cutoff|" +
        @"chat\s?gpt|\bclaude\b|openai|нейросет", O);

    public static readonly Regex Placeholder = new(
        @"\[(?:вставьте|вставить|ваше|ваш|ваша|укажите|добавьте|имя|фио|название|дата|номер|" +
        @"insert|your|add|name|date|company)[^\]\n]{0,50}\]", O);

    public static readonly Regex Markdown = new(
        @"^\s*#{1,6}\s|\*\*[^*\n]{1,80}\*\*|```|^\s*\|.+\|\s*$|\[[^\]\n]+\]\(https?://|^\s*[*]\s+\S", O | RegexOptions.Multiline);

    public static readonly Regex Emoji = new(
        @"[☀-➿]|[\uD83C-\uDBFF][\uDC00-\uDFFF]|⭐|⬆|⤴|⤵", RegexOptions.Compiled);

    /// <summary>Подозрительный alt-текст или имя картинки.</summary>
    public static readonly Regex ImageName = new(
        @"matplotlib|plotly|seaborn|generated|сгенерир|dall|midjourney|chatgpt|openai|gemini|image_gen", O);

    /// <summary>Путь к файлу на компьютере, где собирался документ (python-pptx пишет его в alt-текст).</summary>
    public static readonly Regex PathLike = new(
        @"^(?:/|[a-z]:\\|\\\\)|/home/|/tmp/|/mnt/|/root/|/var/|/users/|\\users\\", O);

    /// <summary>Абзац, целиком состоящий из служебной фразы чат-бота.</summary>
    public static readonly Regex ChatPreamble = new(
        @"^(?:(?:конечно|разумеется|безусловно|certainly|sure|of course|absolutely)[!,.]?\s.{0,120}?\b(?:вот|here)\b" +
        @"|вот (?:обновл|исправл|переработ|доработ|улучш|сокращ|расширен|итогов)\w*\s" +
        @"|надеюсь,? (?:это|эта|данн)\w*\s.{0,40}(?:помо|полез)" +
        @"|(?:если (?:хотите|нужно|потребуется|понадобится)|хотите,? (?:я|чтобы))\b.{0,150}?(?:мог|помог|подготов|сдела|дополн|скажите|напишите|дайте знать)" +
        @"|(?:дайте знать|сообщите|напишите),? (?:если|когда)" +
        @"|(?:here is|here's|below is) (?:the|a|an|your) (?:revised|updated|improved|rewritten|final)" +
        @"|i hope this helps|let me know if|feel free to ask" +
        @"|as an ai\b|как (?:ии|языковая модель|искусственный интеллект)[,\s])", O);

    /// <summary>Последнее предложение абзаца — предложение чат-бота продолжить работу.</summary>
    public static readonly Regex TrailingOffer = new(
        @"(?<=[.!?…:])\s+((?:если (?:хотите|нужно|потребуется|понадобится)|хотите,? (?:я|чтобы)|могу также|" +
        @"if you(?:'d| would) like|would you like me|let me know if)[^.!?]*[.!?]?)\s*$", O);
}
